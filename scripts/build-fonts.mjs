// Builds one canonical set of @font-face rules used by BOTH the production app and the e2e harness's
// routed demo fonts, so the two sides of the frame comparison render with byte-identical fonts.
//
//   src/styles/fonts.css        — for the app: url(...) points at the woff2 copies in src/assets/fonts/
//   scripts/.fonts/fonts.css    — for the harness: url(/fonts/<file>) served by the fixture server
//   scripts/.fonts/fonts/*.woff2 — the woff2 copies the fixture serves
//
// The variable Noto Sans SC package ships family 'Noto Sans SC Variable'; both outputs rename it to
// 'Noto Sans SC', the name the menu's CSS (migrated verbatim from the demo) expects. Only the woff2
// sources are kept (woff fallbacks dropped): every consumer of these rules is a current Chromium.
// Run: node scripts/build-fonts.mjs
import { readFileSync, writeFileSync, mkdirSync, copyFileSync, readdirSync, rmSync } from "node:fs";
import { join } from "node:path";

const SOURCES = [
  { pkg: "@fontsource/rajdhani", css: ["latin-500.css", "latin-600.css", "latin-700.css"] },
  { pkg: "@fontsource-variable/noto-sans-sc", css: ["index.css"], family: { from: "Noto Sans SC Variable", to: "Noto Sans SC" } },
  { pkg: "@fontsource/inter", css: ["latin-500.css"] },
  { pkg: "@fontsource/jetbrains-mono", css: ["latin-400.css", "latin-600.css"] },
];

const root = new URL("..", import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1");
const nodeModules = (pkg) => join(root, "node_modules", pkg);

const needed = new Set();   // woff2 basenames referenced by the collected rules
let rules = "";

for (const src of SOURCES) {
  for (const cssFile of src.css) {
    let css = readFileSync(join(nodeModules(src.pkg), cssFile), "utf8");
    // drop the woff fallback source, keep woff2 as a placeholder
    css = css.replace(/,? url\(\.\/files\/([^)]+\.woff)\) format\('woff'\)/g, "");
    css = css.replace(/url\(\.\/files\/([^)]+\.woff2)\)/g, (_, file) => {
      needed.add(file);
      return `url(__FONT__${file})`;
    });
    if (src.family) css = css.replaceAll(src.family.from, src.family.to);
    rules += css.trimEnd() + "\n\n";
  }
}

// where each needed woff2 comes from (packages use unique file names)
const fileOrigin = new Map();
for (const src of SOURCES) {
  const dir = join(nodeModules(src.pkg), "files");
  for (const f of readdirSync(dir)) if (!fileOrigin.has(f)) fileOrigin.set(f, join(dir, f));
}
const files = [...needed];
for (const f of files) {
  if (!fileOrigin.has(f)) throw new Error("missing font file in packages: " + f);
}

const header = "/* Generated by scripts/build-fonts.mjs — the canonical @font-face set shared by the app and the\n" +
  "   e2e frame-comparison harness (the demo's Google Fonts link is routed to these same files). */\n";

// 1) app copy: src/assets/fonts — Vite bundles and hashes the woff2 copies
const appFontsDir = join(root, "src", "assets", "fonts");
mkdirSync(appFontsDir, { recursive: true });
for (const f of readdirSync(appFontsDir)) rmSync(join(appFontsDir, f));
for (const f of files) copyFileSync(fileOrigin.get(f), join(appFontsDir, f));
writeFileSync(
  join(root, "src", "styles", "fonts.css"),
  header + rules.replaceAll(/__FONT__(.+?\.woff2)/g, "$1").replaceAll("url(", "url(../assets/fonts/"),
);

// 2) harness css: url(/fonts/<file>) + the copies the fixture server serves
const harnessDir = join(root, "src", "test", "frame", ".fonts");
mkdirSync(join(harnessDir, "fonts"), { recursive: true });
for (const f of readdirSync(join(harnessDir, "fonts"))) rmSync(join(harnessDir, "fonts", f));
for (const f of files) copyFileSync(fileOrigin.get(f), join(harnessDir, "fonts", f));
writeFileSync(
  join(harnessDir, "fonts.css"),
  header + rules.replaceAll(/__FONT__(.+?\.woff2)/g, "/fonts/$1"),
);

console.log(`fonts.css: ${files.length} woff2 files, families: Rajdhani / Noto Sans SC / Inter / JetBrains Mono`);
